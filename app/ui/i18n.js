let LANG = "en";
try {
  const saved = localStorage.getItem("lang");
  LANG = saved || ((navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en");
} catch (_) {
  LANG = (navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
}

function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

function t(key, args) {
  const s = (STRINGS[LANG] && STRINGS[LANG][key]) || STRINGS.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (args && k in args ? esc(args[k]) : ""));
}
